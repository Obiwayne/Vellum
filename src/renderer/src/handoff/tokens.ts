// Token files of the bundle: tokens.css (authored values, one block per mode), tokens.json (W3C Design Tokens
// format, one top-level group per mode) and tailwind.css (a Tailwind v4 `@theme` block of the base mode, other
// modes as plain `[data-mode]` overrides). Only the tokens the exported frames use are written.
import type { Doc, Token } from '../model/types'
import type { TokenUse } from '../model/devSpec'
import { tokensCssWithModes } from '../model/modes'
import { BASE_MODE } from '../model/devSpec'

// Token and mode names and values come from the document and end up in CSS selectors and declarations.
// Anything that could close a rule, a comment or a string is neutralised; ordinary values pass untouched.
const MODE_SAFE = /[^A-Za-z0-9_ -]/g
/** A mode name that is safe in a selector, a string and a comment. */
export const safeMode = (mode: string): string => mode.replace(MODE_SAFE, '-').replace(/-{2,}/g, '-').trim() || 'mode'
/** A token value on one line without anything that ends a declaration or a rule. */
export const safeValue = (v: string): string =>
  String(v)
    .replace(/[\u0000-\u001f\u007f\u2028\u2029]+/g, ' ')
    .replace(/\/\*|\*\//g, ' ')
    .replace(/[{}]/g, ' ')
    .replace(/;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
const safeName = (n: string): string | null => (/^--[A-Za-z0-9_-]+$/.test(n) ? n : null)

const header = (what: string): string => `/* ${what} — generated by Vellum from the exported frames; do not edit */\n`

export function tokensCss(doc: Doc, used: TokenUse[]): string {
  const names = new Set(used.map((u) => u.name))
  const clean = (t: Token): Token => ({
    name: t.name,
    value: safeValue(t.value),
    ...(t.modes ? { modes: Object.fromEntries(Object.entries(t.modes).map(([m, v]) => [safeMode(m), safeValue(v)])) } : {})
  })
  const list: Token[] = doc.tokens
    .filter((t) => names.has(t.name) && safeName(t.name))
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    .map(clean)
  const css = tokensCssWithModes({ ...doc, modes: doc.modes?.map(safeMode) }, list, true)
  return header('tokens.css') + (css ? css + '\n' : '/* no tokens are used by the exported frames */\n')
}

type DtcgValue = { $type?: string; $value: string; $extensions?: { vellum: { authored: string } } }
type DtcgGroup = { [key: string]: DtcgGroup | DtcgValue | string }

const isLeaf = (v: unknown): v is DtcgValue => typeof v === 'object' && v !== null && '$value' in (v as object)

function put(group: DtcgGroup, path: string[], leaf: DtcgValue): void {
  let g = group
  for (let i = 0; i < path.length - 1; i++) {
    const key = path[i]
    let next = g[key] as DtcgGroup | DtcgValue | undefined
    if (isLeaf(next)) {
      // a token that is also the prefix of others: keep it under `$root`
      const moved: DtcgGroup = { $root: next as unknown as DtcgGroup }
      g[key] = moved
      next = moved
    }
    if (!next) {
      next = {}
      g[key] = next
    }
    g = next as DtcgGroup
  }
  const last = path[path.length - 1]
  const existing = g[last]
  if (existing && !isLeaf(existing)) (existing as DtcgGroup).$root = leaf as unknown as DtcgGroup
  else g[last] = leaf as unknown as DtcgGroup
}

const dtcgType = (u: TokenUse): string | undefined => (u.type === 'color' ? 'color' : u.type === 'length' ? 'dimension' : u.type === 'number' ? 'number' : undefined)

export function tokensJson(used: TokenUse[], modes: string[]): string {
  const keys = modes.length ? modes : [BASE_MODE]
  const out: DtcgGroup = {}
  for (const mode of keys) {
    const group: DtcgGroup = {}
    for (const u of used) {
      const v = u.values[mode] ?? u.values[keys[0]]
      if (!v) continue
      const path = u.name.replace(/^--/, '').split('-').filter(Boolean)
      if (!path.length) continue
      const leaf: DtcgValue = { $value: u.type === 'color' && v.hex8 ? v.hex8 : v.value }
      const t = dtcgType(u)
      if (t) leaf.$type = t
      if (u.type === 'color' && /^ok(lch|lab)\(/i.test(v.value)) leaf.$extensions = { vellum: { authored: v.value } }
      put(group, path, leaf)
    }
    out[mode] = group
  }
  return JSON.stringify(out, null, 2) + '\n'
}

export function tailwindCss(used: TokenUse[], modes: string[]): string {
  const keys = modes.length ? modes : [BASE_MODE]
  const base = keys[0]
  const decl = (mode: string): string[] =>
    used
      .map((u) => {
        const v = u.values[mode] ?? u.values[base]
        return v && safeName(u.name) ? `  ${u.name}: ${safeValue(v.value)};` : ''
      })
      .filter(Boolean)
  const lines: string[] = [header('tailwind.css'), '/* Tailwind v4: only names in Tailwind\'s theme namespaces (--color-*, --spacing-*, --radius-*, --font-*, ...) become utilities. */', '@theme {']
  if (!used.length) lines.splice(3, 0, '/* no tokens are used by the exported frames */')
  lines.push(...decl(base), '}')
  for (const mode of keys.slice(1)) {
    lines.push('', `/* ${safeMode(mode)} mode: plain overrides, outside @theme */`, `[data-mode="${safeMode(mode)}"] {`, ...decl(mode), '}')
  }
  return lines.join('\n') + '\n'
}
