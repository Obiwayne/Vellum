// Drives the built app (npm run build first): colour styles in colour fields (T30). Create a colour style, pick it in
// the Fill picker (styles first), edit the token and see the frame follow, switch Light/Dark, Detach, "Add as colour
// style" in Selection colors, then text colour and text stroke; each change is one undo step.
// Usage: node scripts/e2e-colour-styles.mjs <out-dir>. Needs `npm i -D playwright`.
import { _electron as electron } from 'playwright'
import { mkdirSync, mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const out = process.argv[2] ?? '.muster-evidence/e2e-colour-styles'
mkdirSync(out, { recursive: true })
const ud = mkdtempSync(join(tmpdir(), 'vellum-e2e-'))
const app = await electron.launch({ args: ['out/main/index.js'], env: { ...process.env, VELLUM_USER_DATA: ud } })
const page = await app.firstWindow()
page.setDefaultTimeout(8000)
const results = []
let n = 0
const shot = async (name) => {
  await page.waitForTimeout(400)
  await page.screenshot({ path: join(out, `${String(++n).padStart(2, '0')}-${name}.png`) })
}
const check = (ok, label) => results.push(`${ok ? 'passed' : 'FAILED'}: ${label}`)
const wait = (ms = 400) => page.waitForTimeout(ms)
const typeText = async (x, y, text) => {
  await page.keyboard.press('t')
  await page.mouse.click(x, y)
  await page.keyboard.type(text)
  await page.keyboard.press('Escape')
}
try {
  await page.waitForTimeout(1500)
  await page.reload()
  await page.waitForTimeout(2500)
  await page.locator('input:not([type=file])').first().fill('Tester')
  await page.getByRole('button', { name: 'Create profile' }).click()
  await page.waitForTimeout(2000)
  await page.getByText('Scratchpad').first().dblclick()
  await page.waitForTimeout(2500)
  await page.keyboard.press('f')
  await page.mouse.move(330, 150)
  await page.mouse.down()
  await page.mouse.move(700, 330, { steps: 6 })
  await page.mouse.up()
  await typeText(350, 175, 'Hello')
  await page.mouse.click(900, 700)
  await page.mouse.click(690, 320) // select the frame
  await wait()
  await shot('frame-selected')
  const frameBg = () =>
    page.evaluate(() => {
      const el = [...document.querySelectorAll('[data-node-id]')].find((e) => e.children.length > 0 && e.textContent.includes('Hello'))
      return getComputedStyle(el).backgroundColor
    })
  const wordColor = () =>
    page.evaluate(() => {
      const el = [...document.querySelectorAll('[data-node-id]')].find((e) => e.children.length === 0 && e.textContent === 'Hello')
      return getComputedStyle(el).color
    })
  const tokensBtn = (i = 0) => page.getByRole('button', { name: 'Tokens', exact: true }).nth(i)
  const fieldToken = () => page.locator('.c-colorrow__token').first().textContent().catch(() => null)
  const hexInput = () => page.locator('.c-colorrow__hex').first()
  const setHex = async (v) => {
    await hexInput().fill(v)
    await page.keyboard.press('Enter')
    await wait(500)
  }

  // A. create a colour style from the frame's white fill
  await page.getByText('Theme', { exact: true }).first().click()
  await wait()
  await page.getByRole('tab', { name: 'Styles' }).click()
  await wait()
  await page.locator('[data-styles="colour"] .lp-styles__head button').click()
  await wait(300)
  await page.keyboard.type('brand')
  await page.keyboard.press('Enter')
  await wait(500)
  check((await page.locator('[data-colour-style="--color-brand"]').count()) === 1, 'colour style "brand" created')
  check((await fieldToken()) === 'brand', `Fill field shows the style name (${await fieldToken()})`)
  await shot('style-created-fill-shows-name')
  // detach it by hand to a literal orange, then pick the style from the picker
  await page.getByRole('tab', { name: 'Styles' }).click().catch(() => {})
  await tokensBtn().click()
  await wait()
  await page.getByRole('button', { name: 'Detach style' }).click()
  await wait(500)
  await setHex('FF8800')
  check((await frameBg()) === 'rgb(255, 136, 0)', `literal fill FF8800 (${await frameBg()})`)
  await shot('literal-orange')
  await tokensBtn().click()
  await wait()
  const listed = await page.locator('.insp-pop__list .insp-listitem').allTextContents()
  check(listed[0] === 'color-brand', `picker lists the colour style first (${listed[0]})`)
  await shot('picker-lists-styles-first')
  await page.locator('.insp-pop__list .insp-listitem', { hasText: 'color-brand' }).click()
  await wait(500)
  check((await fieldToken()) === 'brand', `choosing it shows the style name in the field (${await fieldToken()})`)
  check((await frameBg()) === 'rgb(255, 255, 255)', `frame shows the style's colour (${await frameBg()})`)
  await shot('applied')
  await page.mouse.click(900, 700)
  await page.mouse.click(690, 320)
  await page.keyboard.press('Control+z')
  await wait(500)
  check((await frameBg()) === 'rgb(255, 136, 0)' && (await fieldToken()) === null, `one undo returns the literal (${await frameBg()})`)
  await page.keyboard.press('Control+Shift+z')
  await wait(500)
  check((await fieldToken()) === 'brand', 'redo reapplies the style')

  // B. edit the token in the Styles panel: the frame follows
  await page.locator('[data-colour-style="--color-brand"]').click()
  await wait()
  await shot('token-editor-open')
  const value = page.locator('.lp-token-editor__field', { hasText: 'Value' }).locator('input')
  await value.fill('#112233')
  await page.keyboard.press('Enter')
  await wait(500)
  check((await frameBg()) === 'rgb(17, 34, 51)', `editing the token recolours the frame (${await frameBg()})`)
  await shot('token-edited')
  await page.keyboard.press('Escape')
  // C. Dark mode: brand gets its own Dark value; switching the frame's mode changes the computed colour
  await page.getByRole('tab', { name: 'Tokens' }).click()
  await wait()
  await page.getByRole('button', { name: 'Add token' }).click()
  await page.getByText('Add dark mode').click()
  await wait()
  await page.getByRole('tab', { name: 'Styles' }).click()
  await wait()
  await page.locator('.lp-theme').getByText('Dark', { exact: true }).first().click()
  await wait()
  await page.locator('[data-colour-style="--color-brand"]').click()
  await wait()
  await page.locator('.lp-token-editor__field', { hasText: 'Value' }).locator('input').fill('#ddeeff')
  await page.keyboard.press('Enter')
  await wait(500)
  await shot('dark-value-set')
  await page.keyboard.press('Escape')
  await page.getByText('Design', { exact: true }).first().click()
  await wait()
  await page.getByText('Inherit (Light)').click()
  await wait()
  await shot('mode-select-open')
  await page.getByRole('option', { name: 'Dark' }).click().catch(async () => page.getByText('Dark', { exact: true }).last().click())
  await wait(500)
  check((await frameBg()) === 'rgb(221, 238, 255)', `Dark mode: the frame shows the Dark value (${await frameBg()})`)
  await shot('dark-mode')
  // D. Detach in Dark writes the Dark literal; one undo relinks
  await tokensBtn().click()
  await wait()
  await page.getByRole('button', { name: 'Detach style' }).click()
  await wait(500)
  check((await fieldToken()) === null && (await hexInput().inputValue()).toLowerCase() === 'ddeeff', `Detach in Dark writes the Dark literal (${await hexInput().inputValue()})`)
  await shot('detached-in-dark')
  await page.mouse.click(900, 700)
  await page.mouse.click(690, 320)
  await page.keyboard.press('Control+z')
  await wait(500)
  check((await fieldToken()) === 'brand', 'one undo relinks the field to the style')
  // switching the frame back to Inherit (Light) gives the Light value
  await page.getByText('Dark', { exact: true }).last().click()
  await page.getByText('Inherit (Light)', { exact: true }).last().click()
  await wait(500)
  check((await frameBg()) === 'rgb(17, 34, 51)', `back to Light: the frame shows the Light value (${await frameBg()})`)
  await shot('light-mode')
  // E. Selection colors: "Add as colour style" for the text's literal black, one undo
  await page.mouse.click(900, 700)
  await page.mouse.click(690, 320)
  await wait()
  const sel = page.locator('.c-section', { hasText: 'Selection colors' })
  const textRow = sel.locator('.c-colorrow').nth(1)
  await textRow.getByRole('button', { name: 'Tokens', exact: true }).click()
  await wait()
  await page.getByRole('button', { name: 'Add as colour style' }).click()
  await wait(300)
  await shot('selection-add-as-style')
  await page.locator('.insp-newtoken input').fill('--color-ink')
  await page.locator('.insp-newtoken__ok').click()
  await wait(500)
  const inkRow = await sel.locator('.c-colorrow__token').allTextContents()
  check(inkRow.includes('ink'), `Selection colors now shows the style "ink" (${JSON.stringify(inkRow)})`)
  check((await wordColor()) === 'rgb(0, 0, 0)', `the text keeps its colour (${await wordColor()})`)
  await shot('selection-converted')
  await page.mouse.click(900, 700)
  await page.mouse.click(690, 320)
  await page.keyboard.press('Control+z')
  await wait(500)
  const afterUndo = await sel.locator('.c-colorrow__token').allTextContents()
  check(!afterUndo.includes('ink'), `one undo turns it back into the literal (${JSON.stringify(afterUndo)})`)
  await page.keyboard.press('Control+Shift+z')
  await wait(500)
  // F. text colour and text stroke
  await page.mouse.click(900, 700)
  await page.keyboard.down('Control')
  await page.mouse.click(368, 177)
  await page.keyboard.up('Control')
  await wait()
  await shot('text-selected')
  // text colour: apply "brand", then Detach (writes the Light literal), one undo each
  check((await fieldToken()) === 'ink', 'the text colour field shows the style "ink"')
  await tokensBtn().click()
  await wait()
  const textList = await page.locator('.insp-pop__list .insp-listitem').allTextContents()
  check(textList.slice(0, 3).join() === 'Detach style,color-brand,color-ink', `text colour picker lists the styles (${textList.join(' / ')})`)
  await page.locator('.insp-pop__list .insp-listitem', { hasText: 'color-brand' }).click()
  await wait(500)
  check((await fieldToken()) === 'brand' && (await wordColor()) === 'rgb(17, 34, 51)', `text colour applies the style (${await wordColor()})`)
  await shot('text-colour-applied')
  await tokensBtn().click()
  await wait()
  await page.getByRole('button', { name: 'Detach style' }).click()
  await wait(500)
  check((await fieldToken()) === null && (await hexInput().inputValue()).toLowerCase() === '112233', `text colour Detach writes the literal (${await hexInput().inputValue()})`)
  await shot('text-colour-detached')
  await page.keyboard.press('Control+z')
  await wait(500)
  check((await fieldToken()) === 'brand', 'one undo relinks the text colour')

  // text stroke
  await page.getByRole('button', { name: 'Add stroke' }).last().click()
  await wait()
  const strokeSec = page.locator('.c-section', { has: page.locator('.c-section__title', { hasText: /^Stroke$/ }) })
  await strokeSec.getByRole('button', { name: 'Tokens', exact: true }).click()
  await wait()
  await page.locator('.insp-pop__list .insp-listitem', { hasText: 'color-brand' }).click()
  await wait(500)
  const strokeColour = await page.evaluate(() => {
    const el = [...document.querySelectorAll('[data-node-id]')].find((e) => e.children.length === 0 && e.textContent === 'Hello')
    return getComputedStyle(el).webkitTextStrokeColor
  })
  check((await strokeSec.locator('.c-colorrow__token').textContent()) === 'brand' && strokeColour === 'rgb(17, 34, 51)', `stroke colour applies the style (${strokeColour})`)
  await shot('stroke-applied')
  await strokeSec.getByRole('button', { name: 'Tokens', exact: true }).click()
  await wait()
  await page.getByRole('button', { name: 'Detach style' }).click()
  await wait(500)
  check((await strokeSec.locator('.c-colorrow__token').count()) === 0 && (await strokeSec.locator('.c-colorrow__hex').inputValue()).toLowerCase() === '112233', 'stroke Detach writes the literal')
  await shot('stroke-detached')
  await page.keyboard.press('Control+z')
  await wait(500)
  check((await strokeSec.locator('.c-colorrow__token').textContent()) === 'brand', 'one undo relinks the stroke colour')
} catch (e) {
  results.push(`FAILED: script error: ${String(e.message).slice(0, 400)}`)
  await shot('error').catch(() => {})
} finally {
  console.log(results.join('\n'))
  await Promise.race([app.close(), new Promise((r) => setTimeout(r, 8000))])
  try {
    rmSync(ud, { recursive: true, force: true })
  } catch {
    /* temp dir may still be locked */
  }
  process.exit(0)
}
